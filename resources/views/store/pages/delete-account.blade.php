<x-static-page title="Delete Account">
<p>You can permanently delete your Koru account and its associated data at any time.</p>

<h2>Delete from the mobile app</h2>
<ol>
<li>Open the Koru app and log in with your mobile number.</li>
<li>Go to <strong>Profile</strong>.</li>
<li>Tap <strong>Delete Account</strong>.</li>
<li>Type <strong>DELETE</strong> to confirm.</li>
<li>Tap <strong>Delete Account</strong>. You will be logged out and your account will be removed.</li>
</ol>

<h2>Request deletion by email</h2>
<p>If you cannot access the app, email <a href="mailto:{{ $supportEmail }}">{{ $supportEmail }}</a> from any address with the subject <strong>"Delete my account"</strong> and include your registered mobile number. We will verify the request and delete your account within 7 days.</p>

<h2>What is deleted</h2>
<ul>
<li>Your profile: name, mobile number, email, and profile photo.</li>
<li>Saved addresses, favorites, and login sessions.</li>
</ul>

<h2>What may be retained</h2>
<ul>
<li>Order and payment records required for tax, accounting, and legal purposes, kept only as long as the law requires.</li>
</ul>
